import type { AppSettings, CookieFile } from '@yt-dlp-studio/shared'
import type { EventBus } from './events'
import type { CookieSource } from './ytdlp/args'
import { Buffer } from 'node:buffer'
import fs from 'node:fs/promises'
import path from 'node:path'
import { COOKIES_NONE } from '@yt-dlp-studio/shared'
import { pathExists, writeFileAtomic } from '../utils/fs'
import { createId } from '../utils/id'
import { createLogger } from '../utils/logger'
import { JsonStore } from './store'

const logger = createLogger('cookies')
const MAX_SIZE = 10 * 1024 * 1024
const GENERATED_MARK = 'generated by yt-dlp Studio'

interface ParsedCookie {
  key: string
  line: string
}

interface ParsedFile {
  cookies: ParsedCookie[]
  domains: string[]
  expired: number
}

/** Parse a Netscape cookies.txt file. `#HttpOnly_` prefixed lines are cookies, not comments. */
export function parseCookies(content: string): ParsedFile {
  const cookies: ParsedCookie[] = []
  const domains = new Map<string, number>()
  const now = Date.now() / 1000
  let expired = 0
  for (const raw of content.replace(/^\uFEFF/, '').split(/\r?\n/)) {
    const line = raw.trim()
    if (!line || (line.startsWith('#') && !line.startsWith('#HttpOnly_')))
      continue
    const fields = line.split('\t')
    if (fields.length < 7)
      continue
    const [domainField, , cookiePath, , expiry, name] = fields
    const domain = domainField.replace(/^#HttpOnly_/, '')
    cookies.push({ key: `${domain}\t${cookiePath}\t${name}`, line: fields.slice(0, 6).concat(fields.slice(6).join('\t')).join('\t') })
    const host = domain.replace(/^\./, '').replace(/^www\./, '').toLowerCase()
    domains.set(host, (domains.get(host) ?? 0) + 1)
    const expires = Number(expiry)
    if (expires > 0 && expires < now)
      expired++
  }
  return {
    cookies,
    domains: [...domains.entries()].sort((a, b) => b[1] - a[1]).map(([host]) => host),
    expired,
  }
}

/**
 * Stores several uploaded cookies.txt files (usually one per site) and merges the
 * enabled ones into the single file passed to yt-dlp via `--cookies`.
 */
export class CookieService {
  private store: JsonStore<{ files: CookieFile[] }>
  private chain: Promise<unknown> = Promise.resolve()

  constructor(private readonly dataDir: string, private readonly events: EventBus) {
    this.store = new JsonStore(path.join(this.dir, 'index.json'), { files: [] }, 0)
  }

  private get dir() {
    return path.join(this.dataDir, 'cookies')
  }

  /** Merged file consumed by yt-dlp */
  get mergedFile() {
    return path.join(this.dataDir, 'cookies.txt')
  }

  private fileOf(id: string) {
    return path.join(this.dir, `${id}.txt`)
  }

  async init() {
    const indexExists = await pathExists(this.store.file)
    await this.store.load(raw => ({ files: Array.isArray(raw?.files) ? raw.files : [] }))
    if (indexExists || !await pathExists(this.mergedFile))
      return
    // Migrate the single cookies.txt used by earlier versions
    const legacy = await fs.readFile(this.mergedFile, 'utf8')
    if (legacy.includes(GENERATED_MARK))
      return
    try {
      await this.add('cookies.txt', legacy)
      logger.info('Imported existing cookies.txt')
    }
    catch (error) {
      logger.warn('Could not import existing cookies.txt', { error })
    }
  }

  list() {
    return [...this.store.data.files].sort((a, b) => b.updatedAt - a.updatedAt)
  }

  get hasEnabled() {
    return this.store.data.files.some(file => file.enabled)
  }

  /**
   * Resolve the cookies of a download: an explicitly chosen file (used even when it is
   * disabled for the merged file), none at all, or whatever the global settings say.
   */
  resolve(selection: string | undefined, settings: AppSettings): CookieSource | undefined {
    if (selection === COOKIES_NONE)
      return undefined
    if (selection) {
      const file = this.store.data.files.find(item => item.id === selection)
      if (!file)
        throw new Error('The selected cookies file no longer exists, choose another one in the download options')
      return { file: this.fileOf(file.id) }
    }
    if (settings.cookiesMode === 'file' && this.hasEnabled)
      return { file: this.mergedFile }
    if (settings.cookiesMode === 'browser' && settings.cookiesBrowser)
      return { browser: settings.cookiesBrowser }
    return undefined
  }

  /** Human readable cookies source of a download for the logs (never the cookie values) */
  describe(selection: string | undefined, settings: AppSettings) {
    if (selection === COOKIES_NONE)
      return 'none'
    if (selection)
      return `file: ${this.store.data.files.find(item => item.id === selection)?.name ?? selection}`
    if (settings.cookiesMode === 'file' && this.hasEnabled)
      return 'global: merged files'
    if (settings.cookiesMode === 'browser' && settings.cookiesBrowser)
      return `global: browser ${settings.cookiesBrowser}`
    return 'none'
  }

  /** Add a file. A file with the same name is replaced, so re-exporting a site is easy. */
  add(name: string, content: string) {
    return this.serial(async () => {
      if (Buffer.byteLength(content) > MAX_SIZE)
        throw new Error('Cookies file is too large (max 10 MiB)')
      if (/^\s*[[{]/.test(content))
        throw new Error('JSON cookies are not supported, export in Netscape (cookies.txt) format')
      const parsed = parseCookies(content)
      if (!parsed.cookies.length)
        throw new Error('No cookies found, expected a Netscape cookies.txt file')

      const safeName = path.basename(name).slice(0, 120) || 'cookies.txt'
      const now = Date.now()
      const existing = this.store.data.files.find(file => file.name === safeName)
      const file: CookieFile = {
        id: existing?.id ?? createId(),
        name: safeName,
        domains: parsed.domains,
        count: parsed.cookies.length,
        expired: parsed.expired,
        size: Buffer.byteLength(content),
        enabled: true,
        createdAt: existing?.createdAt ?? now,
        updatedAt: now,
      }
      await writeFileAtomic(this.fileOf(file.id), content)
      this.store.data.files = [...this.store.data.files.filter(item => item.id !== file.id), file]
      await this.commit()
      logger.info(`${existing ? 'Replaced' : 'Added'} cookies file "${file.name}"`, {
        ref: file.id,
        data: { cookies: file.count, expired: file.expired || undefined, domains: file.domains.slice(0, 8).join(', ') },
      })
      return file
    })
  }

  setEnabled(id: string, enabled: boolean) {
    return this.serial(async () => {
      const file = this.store.data.files.find(item => item.id === id)
      if (!file)
        return null
      file.enabled = enabled
      await this.commit()
      logger.info(`${enabled ? 'Enabled' : 'Disabled'} cookies file "${file.name}"`, { ref: file.id })
      return file
    })
  }

  remove(id: string) {
    return this.serial(async () => {
      const removed = this.store.data.files.find(item => item.id === id)
      if (!removed)
        return false
      this.store.data.files = this.store.data.files.filter(item => item.id !== id)
      await fs.rm(this.fileOf(id), { force: true })
      await this.commit()
      logger.info(`Removed cookies file "${removed.name}"`, { ref: id })
      return true
    })
  }

  private serial<T>(task: () => Promise<T>): Promise<T> {
    const next = this.chain.then(task, task)
    this.chain = next.catch(() => {})
    return next
  }

  private async commit() {
    await this.store.flush()
    await this.rebuild()
    this.events.emit({ type: 'cookies:updated', files: this.list() })
  }

  /** Merge enabled files; for duplicate cookies the most recently uploaded file wins */
  private async rebuild() {
    const enabled = this.store.data.files.filter(file => file.enabled).sort((a, b) => a.updatedAt - b.updatedAt)
    if (!enabled.length) {
      await fs.rm(this.mergedFile, { force: true })
      return
    }
    const merged = new Map<string, string>()
    for (const file of enabled) {
      try {
        for (const cookie of parseCookies(await fs.readFile(this.fileOf(file.id), 'utf8')).cookies) {
          merged.delete(cookie.key)
          merged.set(cookie.key, cookie.line)
        }
      }
      catch (error) {
        logger.warn(`Could not read cookies file ${file.name}`, { ref: file.id, error })
      }
    }
    const header = [
      '# Netscape HTTP Cookie File',
      `# This file is ${GENERATED_MARK} from ${enabled.length} uploaded file(s). Changes will be overwritten.`,
      '',
    ]
    await writeFileAtomic(this.mergedFile, `${[...header, ...merged.values()].join('\n')}\n`)
  }
}
